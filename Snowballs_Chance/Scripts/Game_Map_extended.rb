# Game_Map: (Extension)
# ----------------------
# Adds the ability to change the height and width
#===============================================================================
class Game_Map
  #--------------------------------------------------------------------------
  # * Sets height of the map to a given value
  #--------------------------------------------------------------------------
  def height=(value)
    @map.height = value
  end
  
  #--------------------------------------------------------------------------
  # * Sets width of the map to a given value
  #--------------------------------------------------------------------------
  def width=(value)
    @map.width = value
  end
end